      options: {
        ...baseOptions(colors, { horizontal: true }),
        plugins: {
          ...baseOptions(colors, { horizontal: true }).plugins,
          tooltip: {
            ...baseOptions(colors, { horizontal: true }).plugins.tooltip,
            callbacks: {
              label(context) {
                const total = context.dataset.data.reduce((a, b) => a + b, 0);
                return ` ${format(context.raw)} recalls (${pct(context.raw, total)})`;
              },
            },
          },
        },
      },
